"""Static PPM-C tables for the C sender instrument: layout, size, o2 pruning and digest.

The layout is the one the C encoder reads (`ppm_enc.c`). For each order k present, contexts of
length k sorted lexicographically, entries of each context sorted by symbol:

  ppm_ctx{k}  n_ctx * k bytes (omitted for k = 0)
  ppm_off{k}  n_ctx + 1 offsets, width = smallest of {1, 2, 4} bytes holding n_ent
  ppm_sym{k}  n_ent bytes
  ppm_cnt{k}  n_ent counts, width = smallest of {1, 2, 4} bytes holding the largest count

table_bytes = sum_k [n_ctx*k + (n_ctx+1)*w_off + n_ent*(1 + w_cnt)]. The pruning rule is the one of
the design (stage 2): it depends only on training counts, never on a message.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

Counts = dict[bytes, dict[bytes, int]]

_CTYPE = {1: "uint8_t", 2: "uint16_t", 4: "uint32_t"}
MAX_TOTAL = 1 << 23  # same bound as MAX_TOTAL in ppm_model.h


def width(value: int) -> int:
    if value <= 0xFF:
        return 1
    if value <= 0xFFFF:
        return 2
    if value <= 0xFFFFFFFF:
        return 4
    raise ValueError(f"value {value} does not fit in 32 bits")


def restrict(ctx_counts: Counts, order: int) -> Counts:
    return {ctx: dict(syms) for ctx, syms in ctx_counts.items() if len(ctx) <= order and syms}


def _order_bytes(k: int, n_ctx: int, n_ent: int, max_count: int) -> int:
    if n_ctx == 0:
        return 0
    return n_ctx * k + (n_ctx + 1) * width(n_ent) + n_ent * (1 + width(max_count))


def _order_stats(ctx_counts: Counts) -> dict[int, tuple[int, int, int]]:
    stats: dict[int, list[int]] = {}
    for ctx, syms in ctx_counts.items():
        if not syms:
            continue
        s = stats.setdefault(len(ctx), [0, 0, 0])
        s[0] += 1
        s[1] += len(syms)
        s[2] = max(s[2], max(syms.values()))
    return {k: tuple(v) for k, v in stats.items()}


def table_bytes(ctx_counts: Counts) -> int:
    return sum(_order_bytes(k, *s) for k, s in _order_stats(ctx_counts).items())


def prune_o2(ctx_counts_o2: Counts, target_bytes: int) -> tuple[Counts, bool, int]:
    """Remove order-2 entries by (count, ctx+sym) ascending; stop at the first size <= target.

    Returns (pruned, reached, removed). Orders 0 and 1 are never touched. If even removing every
    order-2 entry leaves the tables above the target, returns the order-0/1 model and reached=False.
    """
    work = {ctx: dict(syms) for ctx, syms in ctx_counts_o2.items() if syms}
    if table_bytes(work) <= target_bytes:
        return work, True, 0
    base = table_bytes({c: s for c, s in work.items() if len(c) < 2})
    order = sorted((n, ctx + sym, ctx, sym) for ctx, syms in work.items() if len(ctx) == 2
                   for sym, n in syms.items())
    n_ctx = sum(1 for c in work if len(c) == 2)
    n_ent = len(order)
    left = {c: len(s) for c, s in work.items() if len(c) == 2}
    for i, (_, _, ctx, sym) in enumerate(order):
        del work[ctx][sym]
        n_ent -= 1
        left[ctx] -= 1
        if left[ctx] == 0:
            del work[ctx]
            n_ctx -= 1
        # removal is in ascending count order, so the largest remaining count is the last one
        max_count = order[-1][0] if n_ent else 0
        if base + _order_bytes(2, n_ctx, n_ent, max_count) <= target_bytes:
            return work, True, i + 1
    return work, False, len(order)


def counts_sha256(ctx_counts: Counts) -> str:
    lines = sorted((ctx, sym, n) for ctx, syms in ctx_counts.items() for sym, n in syms.items())
    text = "".join(f"{ctx.hex()} {sym.hex()} {n}\n" for ctx, sym, n in lines)
    return hashlib.sha256(text.encode()).hexdigest()


def _c_array(ctype: str, name: str, values: list[int]) -> str:
    body = ",".join(str(v) for v in values)
    return f"static const {ctype} {name}[{len(values)}] = {{{body}}};\n"


def emit_header(ctx_counts: Counts, order: int, path: Path) -> int:
    """Write the C header for `ctx_counts` restricted to `order`; return table_bytes.

    PPM_ORDER is the highest order actually present (an o2 model pruned to nothing is an o1 model).
    """
    model = restrict(ctx_counts, order)
    worst = max(sum(s.values()) + len(s) for s in model.values())
    if worst >= MAX_TOTAL:
        raise ValueError(f"context total {worst} >= 2^23: the 40-bit coder in ppm_model.h would overflow")
    stats = _order_stats(model)
    top = max(stats)
    out = ["/* generated by scripts/sender_memory/ppm_tables.py; do not edit */\n",
           "#include <stdint.h>\n", f"#define PPM_ORDER {top}\n"]
    for k in range(top + 1):
        if k not in stats:
            raise ValueError(f"order {k} missing below the top order {top}")
        n_ctx, n_ent, max_count = stats[k]
        ctxs = sorted(c for c in model if len(c) == k)
        offs, syms, cnts = [0], [], []
        for c in ctxs:
            for s in sorted(model[c]):
                syms.append(s[0])
                cnts.append(model[c][s])
            offs.append(len(syms))
        out.append(f"#define PPM_NCTX{k} {n_ctx}\n")
        out.append(f"typedef {_CTYPE[width(n_ent)]} ppm_off{k}_t;\n")
        out.append(f"typedef {_CTYPE[width(max_count)]} ppm_cnt{k}_t;\n")
        if k:
            out.append(_c_array("uint8_t", f"ppm_ctx{k}", [b for c in ctxs for b in c]))
        out.append(_c_array(f"ppm_off{k}_t", f"ppm_off{k}", offs))
        out.append(_c_array("uint8_t", f"ppm_sym{k}", syms))
        out.append(_c_array(f"ppm_cnt{k}_t", f"ppm_cnt{k}", cnts))
    path.write_text("".join(out))
    return table_bytes(model)
